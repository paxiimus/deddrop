#!/usr/bin/env python3
"""Writes the UK IP ranges as a Caddy `remote_ip` line, for the UK block
that deploy.sh sets up when BLOCK_UK=true.

    python3 scripts/uk_ip_ranges.py /etc/caddy/deaddrop/uk-ranges

Data: DB-IP "IP to Country Lite" (CC BY 4.0, attribution on the 451 page),
updated monthly; deploy.sh refreshes it weekly via cron. Exits non-zero
and leaves the existing file untouched on any failure, so a bad download
can never silently unblock the UK.
"""
import csv
import gzip
import io
import ipaddress
import os
import sys
import urllib.request
from datetime import date

URL = "https://download.db-ip.com/free/dbip-country-lite-{}.csv.gz"
COUNTRY = "GB"
MIN_RANGES = 1000  # the UK has tens of thousands; fewer means the data is wrong


def months_back(n):
    d = date.today().replace(day=1)
    for _ in range(n):
        yield d.strftime("%Y-%m")
        d = (d.replace(day=1) - date.resolution).replace(day=1)


def download():
    # The current month's file appears some days into the month.
    for month in months_back(3):
        try:
            req = urllib.request.Request(URL.format(month), headers={"User-Agent": "deaddrop-geoblock"})
            with urllib.request.urlopen(req, timeout=120) as r:
                return month, gzip.decompress(r.read()).decode()
        except Exception as e:
            print(f"{month}: {e}", file=sys.stderr)
    sys.exit("Couldn't download DB-IP data; keeping the existing list.")


def uk_networks(text):
    nets = []
    for row in csv.reader(io.StringIO(text)):
        # Lite CSV is "start,end,country"; tolerate the longer layout too.
        cc = row[2] if len(row) == 3 else row[4] if len(row) > 4 else ""
        if cc == COUNTRY:
            first, last = ipaddress.ip_address(row[0]), ipaddress.ip_address(row[1])
            nets.extend(ipaddress.summarize_address_range(first, last))
    v4 = ipaddress.collapse_addresses(n for n in nets if n.version == 4)
    v6 = ipaddress.collapse_addresses(n for n in nets if n.version == 6)
    return [*v4, *v6]


def main():
    dest = sys.argv[1]
    month, text = download()
    nets = uk_networks(text)
    if len(nets) < MIN_RANGES:
        sys.exit(f"Only {len(nets)} UK ranges in the {month} data; refusing to write a list that small.")
    tmp = dest + ".tmp"
    with open(tmp, "w") as f:
        f.write(f"# UK IP ranges, DB-IP {month} (CC BY 4.0). Generated by scripts/uk_ip_ranges.py.\n")
        f.write("remote_ip " + " ".join(map(str, nets)) + "\n")
    os.replace(tmp, dest)
    print(f"{len(nets)} UK ranges from DB-IP {month} -> {dest}")


if __name__ == "__main__":
    main()
